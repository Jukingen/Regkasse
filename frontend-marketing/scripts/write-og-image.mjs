const WIDTH = 1200;
const HEIGHT = 630;
const SCALE = 7;
const GAP = 6;

function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i += 1) {
    c ^= buf[i];
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  }
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

function textWidth(text) {
  return text.length * (5 * SCALE + GAP) - GAP;
}

function drawText(pixels, text, x, y) {
  let cursor = x;
  for (const char of text) {
    const glyph = FONT[char] ?? FONT[' '];
    for (let row = 0; row < 7; row += 1) {
      for (let col = 0; col < 5; col += 1) {
        if (glyph[row][col] !== '1') continue;
        for (let sy = 0; sy < SCALE; sy += 1) {
          for (let sx = 0; sx < SCALE; sx += 1) {
            const px = cursor + col * SCALE + sx;
            const py = y + row * SCALE + sy;
            if (px < 0 || py < 0 || px >= WIDTH || py >= HEIGHT) continue;
            const offset = (py * WIDTH + px) * 3;
            pixels[offset] = 255;
            pixels[offset + 1] = 255;
            pixels[offset + 2] = 255;
          }
        }
      }
    }
    cursor += 5 * SCALE + GAP;
  }
}

const pixels = Buffer.alloc(WIDTH * HEIGHT * 3);
for (let i = 0; i < pixels.length; i += 3) {
  pixels[i] = 0x1f;
  pixels[i + 1] = 0x7a;
  pixels[i + 2] = 0x4d;
}

const line1 = 'Regkasse';
const line2 = 'Die Kasse für jede Branche';
drawText(pixels, line1, Math.round((WIDTH - textWidth(line1)) / 2), 230);
drawText(pixels, line2, Math.round((WIDTH - textWidth(line2)) / 2), 330);

const raw = Buffer.alloc((WIDTH * 3 + 1) * HEIGHT);
for (let y = 0; y < HEIGHT; y += 1) {
  const rowStart = y * (WIDTH * 3 + 1);
  raw[rowStart] = 0;
  pixels.copy(raw, rowStart + 1, y * WIDTH * 3, (y + 1) * WIDTH * 3);
}

const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(WIDTH, 0);
ihdr.writeUInt32BE(HEIGHT, 4);
ihdr[8] = 8;
ihdr[9] = 2;
const png = Buffer.concat([
  Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
  chunk('IHDR', ihdr),
  chunk('IDAT', deflateSync(raw)),
  chunk('IEND', Buffer.alloc(0)),
]);

